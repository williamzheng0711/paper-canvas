const dictionaries: Record<Language, Messages> = {
  en,
  'zh-Hans': zhHans,
  'zh-Hant': zhHant,
};

let activeLanguage: Language = 'zh-Hant';

export function isLanguage(value: unknown): value is Language {
  return typeof value === 'string' && supportedLanguages.includes(value as Language);
}

export function detectLanguage(languages: readonly string[] = navigator.languages): Language {
  for (const language of languages) {
    const normalized = language.toLowerCase();
    if (normalized.startsWith('zh')) {
      if (/-(cn|sg|hans)(?:-|$)/.test(normalized)) return 'zh-Hans';
      return 'zh-Hant';
    }
    if (normalized.startsWith('en')) return 'en';
  }
  return 'en';
}

export function setCurrentLanguage(language: Language): void {
  activeLanguage = language;
}

export function getMessages(language: Language = activeLanguage): Messages {
  return dictionaries[language];
}
